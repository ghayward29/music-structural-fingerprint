"""
train_classifier.py — train a CNN to distinguish human-composed vs AI-generated
piano rolls.

Requires piano-roll PNGs already generated by make_rolls.py:
    data/rolls/human/   →  label 0 (human-composed)
    data/rolls/ai/      →  label 1 (AI-generated)

Outputs:
    classifier/model.pth            — trained model weights
    classifier/training_curves.png  — accuracy plot over epochs

Usage:
    python train_classifier.py
    python train_classifier.py --rolls data/rolls/ --epochs 30
"""

import argparse
import glob
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader, random_split
from PIL import Image

from roll_utils import ROLL_TRANSFORM   # shared transform — must match predict.py

# ---------------------------------------------------------------------------
# Hyper-parameters
# ---------------------------------------------------------------------------

BATCH_SIZE    = 16
LEARNING_RATE = 1e-3
SEED          = 42


# ---------------------------------------------------------------------------
# Dataset
# ---------------------------------------------------------------------------

class PianoRollDataset(Dataset):
    """
    Loads grayscale piano-roll PNGs from two labelled folders.

    We use a custom Dataset rather than torchvision.datasets.ImageFolder so we
    can guarantee the label mapping regardless of alphabetical folder order:
        human → 0
        ai    → 1
    ImageFolder assigns labels alphabetically ('ai'=0, 'human'=1 by default),
    which would invert the probability scale expected by predict.py.
    """

    def __init__(self, human_dir: str, ai_dir: str):
        self.samples: list[tuple[str, int]] = []

        for path in sorted(glob.glob(os.path.join(human_dir, "*.png"))):
            self.samples.append((path, 0))   # label 0 = human
        for path in sorted(glob.glob(os.path.join(ai_dir, "*.png"))):
            self.samples.append((path, 1))   # label 1 = ai

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int):
        path, label = self.samples[idx]
        img = Image.open(path)
        tensor = ROLL_TRANSFORM(img)
        # BCELoss expects float targets
        return tensor, torch.tensor(label, dtype=torch.float32)


# ---------------------------------------------------------------------------
# Model
# ---------------------------------------------------------------------------

class PianoRollCNN(nn.Module):
    """
    Lightweight binary CNN for piano-roll classification.

    Architecture:
        Conv1 (1→16, 3×3, pad=1) → ReLU → MaxPool(2×2)   # 16 × 64 × 256
        Conv2 (16→32, 3×3, pad=1) → ReLU → MaxPool(2×2)  # 32 × 32 × 128
        AdaptiveAvgPool2d(4×4)                             # 32 × 4 × 4
        Flatten → Linear(512, 1) → Sigmoid

    AdaptiveAvgPool is placed before the FC layer to collapse the large
    spatial dimensions (32×128 after two pooling steps) to a fixed 4×4
    spatial grid.  Without it, the FC weight matrix would be ~4 M parameters,
    which is excessive for a dataset of this size and would overfit badly.
    The pool also makes the architecture resolution-agnostic — if the image
    size ever changes, only the pool needs adjustment.

    We use a single FC layer (512 → 1) as specified.  Sigmoid converts the
    raw logit to a probability in [0, 1].
    """

    def __init__(self):
        super().__init__()
        self.conv1 = nn.Sequential(
            nn.Conv2d(1, 16, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),
        )
        self.conv2 = nn.Sequential(
            nn.Conv2d(16, 32, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.MaxPool2d(2, 2),
        )
        # Collapse spatial dims so the FC layer has a fixed, small input size.
        self.pool = nn.AdaptiveAvgPool2d((4, 4))
        self.fc   = nn.Linear(32 * 4 * 4, 1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.conv1(x)
        x = self.conv2(x)
        x = self.pool(x)
        x = x.view(x.size(0), -1)       # flatten to (batch, 512)
        return torch.sigmoid(self.fc(x)) # output in [0, 1]


# ---------------------------------------------------------------------------
# Training helpers
# ---------------------------------------------------------------------------

def _accuracy(preds: torch.Tensor, labels: torch.Tensor) -> float:
    """Binary accuracy: threshold predictions at 0.5."""
    return ((preds.squeeze() > 0.5) == labels.bool()).float().mean().item()


def run_epoch(model, loader, criterion, optimizer=None, device="cpu"):
    """
    One pass over a DataLoader.  If optimizer is None the pass is eval-only
    (no gradient updates).  Returns (mean_loss, mean_accuracy).
    """
    training = optimizer is not None
    model.train(training)

    total_loss, total_acc, n_batches = 0.0, 0.0, 0
    with torch.set_grad_enabled(training):
        for imgs, labels in loader:
            imgs, labels = imgs.to(device), labels.to(device)
            preds = model(imgs)
            loss  = criterion(preds.squeeze(), labels)

            if training:
                optimizer.zero_grad()
                loss.backward()
                optimizer.step()

            total_loss += loss.item()
            total_acc  += _accuracy(preds, labels)
            n_batches  += 1

    return total_loss / n_batches, total_acc / n_batches


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Train a CNN classifier on piano-roll PNGs.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--rolls",  default="data/rolls",
                        help="Root folder containing human/ and ai/ sub-folders")
    parser.add_argument("--epochs", type=int, default=20)
    parser.add_argument("--batch",  type=int, default=BATCH_SIZE)
    parser.add_argument("--lr",     type=float, default=LEARNING_RATE)
    args = parser.parse_args()

    human_dir = os.path.join(args.rolls, "human")
    ai_dir    = os.path.join(args.rolls, "ai")
    out_dir   = "classifier"
    os.makedirs(out_dir, exist_ok=True)

    # --- data ---
    dataset = PianoRollDataset(human_dir, ai_dir)
    if len(dataset) < 2:
        print(
            "Not enough images to train — run make_rolls.py first to populate "
            f"{human_dir}/ and {ai_dir}/.",
            file=sys.stderr,
        )
        sys.exit(1)

    torch.manual_seed(SEED)
    n_train = max(1, int(0.8 * len(dataset)))
    n_val   = len(dataset) - n_train
    train_set, val_set = random_split(dataset, [n_train, n_val])

    train_loader = DataLoader(train_set, batch_size=args.batch, shuffle=True)
    val_loader   = DataLoader(val_set,   batch_size=args.batch, shuffle=False)

    n_human = sum(1 for _, lbl in dataset.samples if lbl == 0)
    n_ai    = sum(1 for _, lbl in dataset.samples if lbl == 1)
    print(f"Dataset: {len(dataset)} images  ({n_human} human, {n_ai} AI)")
    print(f"Train: {n_train}  Val: {n_val}")

    # --- model ---
    device    = "cuda" if torch.cuda.is_available() else "cpu"
    model     = PianoRollCNN().to(device)
    criterion = nn.BCELoss()
    # Adam is a safe default: adaptive learning rates handle the relatively
    # small dataset without requiring careful LR scheduling.
    optimizer = torch.optim.Adam(model.parameters(), lr=args.lr)

    print(f"\nTraining on {device} for {args.epochs} epochs\n")
    print(f"{'Epoch':>6}  {'Train Loss':>10}  {'Train Acc':>9}  {'Val Loss':>8}  {'Val Acc':>7}")
    print("-" * 52)

    train_accs, val_accs = [], []

    for epoch in range(1, args.epochs + 1):
        tr_loss, tr_acc = run_epoch(model, train_loader, criterion, optimizer, device)
        vl_loss, vl_acc = run_epoch(model, val_loader,   criterion, None,      device)

        train_accs.append(tr_acc)
        val_accs.append(vl_acc)

        print(f"{epoch:>6}  {tr_loss:>10.4f}  {tr_acc:>9.3f}  {vl_loss:>8.4f}  {vl_acc:>7.3f}")

    # --- save model ---
    model_path = os.path.join(out_dir, "model.pth")
    torch.save(model.state_dict(), model_path)
    print(f"\nModel saved → {model_path}")

    # --- plot accuracy curves ---
    fig, ax = plt.subplots(figsize=(8, 4))
    epochs  = range(1, args.epochs + 1)
    ax.plot(epochs, train_accs, label="Train accuracy",      color="#6366f1")
    ax.plot(epochs, val_accs,   label="Validation accuracy", color="#f59e0b", linestyle="--")
    ax.set_xlabel("Epoch")
    ax.set_ylabel("Accuracy")
    ax.set_title("PianoRollCNN — training curves")
    ax.legend()
    ax.grid(True, alpha=0.3)
    ax.set_ylim(0, 1.05)

    curve_path = os.path.join(out_dir, "training_curves.png")
    plt.tight_layout()
    plt.savefig(curve_path, dpi=150)
    plt.close(fig)
    print(f"Training curves saved → {curve_path}")


if __name__ == "__main__":
    main()
